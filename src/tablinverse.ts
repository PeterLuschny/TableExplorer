/**
 * Provides functions to invert lower triangular integer matrices.
 *
 * Functions:
 *   InvertMatrix(L, check?): bigint[][] — inverts a lower triangular bigint matrix.
 *   InvertTriangle(r, dim): bigint[][] — inverts a triangle given by a row generator.
 *
 * All matrix values are bigint. Row generators follow the same contract as in tabltypes:
 * r(n) returns a bigint[] of length n+1 for n >= 0.
 */

// No import from tabltypes to avoid circular dependencies.
// rowgen type is inlined: (n: number) => bigint[]

/**
 * Calculates the integer inverse of a lower triangular matrix.
 *
 * The algorithm uses forward substitution starting from an identity matrix.
 * When check is true (default), each pivot entry is verified to be non-zero and
 * to divide the current working value exactly — returning [] if not.
 *
 * Note: designed for triangles whose diagonal entries are all 1 (or ±1),
 * which guarantees an integer inverse. For such inputs the check is a
 * safety guard; passing check=false skips it.
 *
 * @param L     Lower triangular matrix: L[k] has at least k+1 entries.
 * @param check Verify integer-inverse existence (default: true).
 * @returns     Lower triangular integer inverse, or [] if it does not exist.
 */
export function InvertMatrix(
    L: bigint[][],
    check: boolean = true
): bigint[][] {
    const n = L.length;

    // Build n×n identity matrix
    const inv: bigint[][] = Array.from({ length: n }, (_, i) =>
        Array.from({ length: n }, (_, j) => (i === j ? 1n : 0n))
    );

    for (let k = 0; k < n; k++) {
        for (let j = 0; j < n; j++) {
            for (let i = 0; i < k; i++) {
                inv[k][j] -= inv[i][j] * L[k][i];
            }
            if (check) {
                const a = inv[k][j];
                const b = L[k][k];
                if (b === 0n) return [];
                const r = a % b;
                if (r !== 0n) return [];
            }
        }
    }

    // Return lower-triangular portion: row n has n+1 entries
    return inv.map((row, n) => row.slice(0, n + 1));
}

/**
 * Inverts a triangular matrix generated by a row function.
 *
 * @param r   Row generator: r(n) returns bigint[] of length n+1 for n >= 0.
 * @param dim Number of rows.
 * @returns   Integer inverse as a lower triangular array, or [] if it does not exist.
 */
export function InvertTriangle(
    r: (n: number) => bigint[],
    dim: number
): bigint[][] {
    const M: bigint[][] = Array.from({ length: dim }, (_, n) => [...r(n)]);
    return InvertMatrix(M, true);
}
